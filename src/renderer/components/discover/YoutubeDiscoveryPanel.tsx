/**
 * YouTube discovery — the console body for Phase 8 item 3.
 *
 * Composed into `DiscoverContent.tsx`'s existing panels rather than mounted as a
 * fourth page, so all three hosts of that console (the Scraper's Discover page,
 * Blanc's discover panel, and the Media Center's discover tab) get this surface
 * without any of them being edited.
 *
 * All judgement lives in `shared/youtubeDiscovery.ts`; this file renders it and
 * owns the two explicit user actions the feature has:
 *
 *   - **Check captions** — one `yt-dlp --skip-download` extraction for one
 *     video, which is the only way to learn whether a caption track was written
 *     by a person or generated by ASR.
 *   - **Add to playlist manager** — hands the video to `main/ytPlaylists.ts`,
 *     metadata only.
 *
 * Nothing here downloads media, and nothing here runs on mount: a search happens
 * when the user presses Search, and a probe happens when the user asks for one.
 */

