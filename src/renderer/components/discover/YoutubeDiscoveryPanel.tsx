export function useYoutubeDiscovery(level: StudyLevel, enabled = true): YoutubeDiscoveryState {
  const initial = useMemo(readPrefs, []);

  const [mode, setModeState] = useState<YoutubeDiscoveryMode>(initial.mode);
  const [query, setQuery] = useState('');
  const [candidates, setCandidates] = useState<YoutubeDiscoveryCandidate[]>([]);
  const [loadState, setLoadState] = useState<YoutubeLoadState>('idle');
  const [message, setMessage] = useState('');
  const [view, setView] = useState<YoutubeView>('results');
  const [selectedId, setSelectedId] = useState<string | null>(null);
  const [insights, setInsights] = useState<Record<string, VideoInsight>>({});
  const [busyVideoId, setBusyVideoId] = useState<string | null>(null);
  const [notice, setNotice] = useState('');
  /** A "Check captions" that failed, said beside the video it was for (audit r2 #24). */
  const [probeError, setProbeError] = useState<{ videoId: string; message: string } | null>(null);
  const [shortlist, setShortlist] = useState<YoutubeShortlistEntry[]>([]);
  const [requireHumanCaptions, setRequireHumanCaptionsState] = useState(initial.requireHumanCaptions);
  const [hideLive, setHideLiveState] = useState(initial.hideLive);

  useEffect(() => {
    setShortlist(loadYoutubeShortlist());
    return onShortlistChanged(() => setShortlist(loadYoutubeShortlist()));
  }, []);

  const submit = useCallback(() => {
    const trimmed = query.trim();
    if (!trimmed || !enabled) return;
    setLoadState('loading');
    setMessage('');
    setView('results');
    const request = mode === 'channel'
      ? window.api?.ytDiscoveryChannel?.(trimmed)
      : window.api?.ytDiscoverySearch?.(trimmed);
    if (!request) {
      setLoadState('error');
      setMessage('');
      return;
    }
    void request
      .then((reply) => {
        setCandidates(reply.candidates ?? []);
        setMessage(reply.message ?? '');
        setLoadState(reply.state);
      })
      .catch((error: unknown) => {
        setCandidates([]);
        setMessage(error instanceof Error ? error.message : String(error));
        setLoadState('error');
      });
  }, [enabled, mode, query]);

  // Memoized rather than derived inline: `.map()` returns a fresh array every
  // render, which would make the three memos below recompute on every keystroke
  // in the search box.
  const source = useMemo(
    () => (view === 'shortlist' ? shortlist.map((entry) => entry.candidate) : candidates),
    [view, shortlist, candidates],
  );

  // Signals first, because channel consistency is computed *from* the signal set
  // and then fed back into scoring — a channel is only "consistent" relative to
  // what has actually been probed.
  const signalled = useMemo(
    () => source.map((candidate) => ({
      candidate,
      signals: deriveStudySignals(candidate, insights[candidate.videoId]?.probe ?? null, {
        target: 'ja',
        charsPerMinute: insights[candidate.videoId]?.charsPerMinute,
      }),
    })),
    [source, insights],
  );

  const channels = useMemo(() => {
    const rows = summariseChannelConsistency(signalled);
    return new Map(rows.map((row) => [row.channelId, row]));
  }, [signalled]);

  const results = useMemo(
    () => rankYoutubeCandidates(signalled, { level, consistency: channels, requireHumanCaptions, hideLive }),
    [signalled, level, channels, requireHumanCaptions, hideLive],
  );

  const selected = useMemo(
    () => results.find((entry) => entry.candidate.videoId === selectedId) ?? null,
    [results, selectedId],
  );

  const shortlistIds = useMemo(() => new Set(shortlist.map((entry) => entry.id)), [shortlist]);

  const setMode = useCallback((next: YoutubeDiscoveryMode) => {
    setModeState(next);
    writePrefs({ ...readPrefs(), mode: next });
  }, []);

  const setRequireHumanCaptions = useCallback((next: boolean) => {
    setRequireHumanCaptionsState(next);
    writePrefs({ ...readPrefs(), requireHumanCaptions: next });
  }, []);

  const setHideLive = useCallback((next: boolean) => {
    setHideLiveState(next);
    writePrefs({ ...readPrefs(), hideLive: next });
  }, []);

  const probe = useCallback((videoId: string) => {
    if (!window.api?.ytDiscoveryProbe) return;
    setBusyVideoId(videoId);
    setNotice('');
    setProbeError(null);
    void window.api.ytDiscoveryProbe(videoId)
      .then((reply) => {
        if (reply.probe) {
          setInsights((prev) => ({
            ...prev,
            [videoId]: { ...prev[videoId], probe: reply.probe ?? undefined },
          }));
        } else {
          setMessage(reply.message ?? '');
          setProbeError({ videoId, message: reply.message ?? '' });
          if (reply.state === 'tool-missing') setLoadState('tool-missing');
        }
      })
      .catch((error: unknown) =>
        setProbeError({ videoId, message: error instanceof Error ? error.message : String(error) }),
      )
      .finally(() => setBusyVideoId(null));
  }, []);

  const handoff = useCallback((candidate: YoutubeDiscoveryCandidate) => {
    if (!window.api?.ytAddVideoByUrl) return;
    setBusyVideoId(candidate.videoId);
    setNotice('');
    void window.api.ytAddVideoByUrl(candidate.url)
      .then((reply) => {
        if (reply.ok) {
          setInsights((prev) => ({
            ...prev,
            [candidate.videoId]: { ...prev[candidate.videoId], managedVideoId: reply.videoId },
          }));
        }
        setNotice(reply.ok ? 'handoffOk' : 'handoffFailed');
      })
      .catch(() => setNotice('handoffFailed'))
      .finally(() => setBusyVideoId(null));
  }, []);

  /**
   * Fetches the caption file for an already-handed-off video and measures pace.
   *
   * Two steps rather than one button that also adds the video: adding to the
   * playlist manager is a real change to the user's library and must not be a
   * side effect of asking a question about speech rate.
   */
  const measurePace = useCallback((candidate: YoutubeDiscoveryCandidate) => {
    const managedVideoId = insights[candidate.videoId]?.managedVideoId;
    const fetchSubs = window.api?.ytFetchSubsOnly;
    const readCaptions = window.api?.ytCachedCaptionText;
    if (!managedVideoId || !fetchSubs || !readCaptions) return;
    setBusyVideoId(candidate.videoId);
    setNotice('');
    void fetchSubs([managedVideoId])
      .then((reply) => {
        // A fetch main stopped at its deadline is not "no captions": say it
        // timed out, so a retry is the obvious next step.
        if (reply.results.some((result) => result.code === 'timeout')) {
          setNotice('paceTimedOut');
          return null;
        }
        return readCaptions(candidate.videoId);
      })
      .then((cached) => {
        if (!cached) return;
        const charsPerMinute = cached.text ? estimateSpeechRate(parseSubtitles(cached.text), 'ja') : undefined;
        if (typeof charsPerMinute !== 'number') {
          setNotice('paceUnavailable');
          return;
        }
        setInsights((prev) => ({
          ...prev,
          [candidate.videoId]: { ...prev[candidate.videoId], charsPerMinute },
        }));
      })
      .catch(() => setNotice('paceUnavailable'))
      .finally(() => setBusyVideoId(null));
  }, [insights]);

  const toggleShortlist = useCallback((candidate: YoutubeDiscoveryCandidate) => {
    const id = youtubeCandidateId(candidate);
    if (loadYoutubeShortlist().some((entry) => entry.id === id)) removeFromShortlist(id);
    else addToShortlist(candidate);
    setShortlist(loadYoutubeShortlist());
  }, []);

  const select = useCallback((videoId: string | null) => setSelectedId(videoId), []);

  return {
    mode,
    setMode,
    query,
    setQuery,
    submit,
    loadState,
    message,
    view,
    setView,
    results,
    channels,
    selected,
    select,
    insights,
    busyVideoId,
    probe,
    handoff,
    measurePace,
    notice,
    probeError,
    shortlist,
    shortlistIds,
    toggleShortlist,
    requireHumanCaptions,
    setRequireHumanCaptions,
    hideLive,
    setHideLive,
  };
}

