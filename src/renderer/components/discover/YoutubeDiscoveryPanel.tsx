/** The wire states, plus the two only a console has: nothing asked, and in flight. */
export type YoutubeLoadState = YoutubeFetchState | 'idle' | 'loading';
export type YoutubeView = 'results' | 'shortlist';

/** Per-video extras the console accumulates as the user asks for them. */
interface VideoInsight {
  probe?: YoutubeProbe;
  /** Target-script characters per minute, once a caption file has been read. */
  charsPerMinute?: number;
  /** The playlist-manager video id, once handed off. */
  managedVideoId?: string;
}

export interface YoutubeDiscoveryState {
  mode: YoutubeDiscoveryMode;
  setMode: (mode: YoutubeDiscoveryMode) => void;
  query: string;
  setQuery: (value: string) => void;
  submit: () => void;
  loadState: YoutubeLoadState;
  message: string;
  view: YoutubeView;
  setView: (view: YoutubeView) => void;
  results: YoutubeRanking[];
  channels: Map<string, YoutubeChannelConsistency>;
  selected: YoutubeRanking | null;
  select: (videoId: string | null) => void;
  insights: Record<string, VideoInsight>;
  busyVideoId: string | null;
  probe: (videoId: string) => void;
  handoff: (candidate: YoutubeDiscoveryCandidate) => void;
  measurePace: (candidate: YoutubeDiscoveryCandidate) => void;
  notice: string;
  /** The last "Check captions" that failed, and for which video. */
  probeError: { videoId: string; message: string } | null;
  shortlist: YoutubeShortlistEntry[];
  shortlistIds: Set<string>;
  toggleShortlist: (candidate: YoutubeDiscoveryCandidate) => void;
  requireHumanCaptions: boolean;
  setRequireHumanCaptions: (value: boolean) => void;
  hideLive: boolean;
  setHideLive: (value: boolean) => void;
}

const PREFS_KEY = 'jp-youtube-discovery-prefs-v1';

interface YoutubePrefs {
  mode: YoutubeDiscoveryMode;
  requireHumanCaptions: boolean;
  hideLive: boolean;
}

const DEFAULT_PREFS: YoutubePrefs = { mode: 'search', requireHumanCaptions: false, hideLive: true };

function readPrefs(): YoutubePrefs {
  try {
    const raw = localStorage.getItem(PREFS_KEY);
    if (!raw) return DEFAULT_PREFS;
    const parsed: unknown = JSON.parse(raw);
    if (typeof parsed !== 'object' || parsed === null) return DEFAULT_PREFS;
    const candidate = parsed as Partial<YoutubePrefs>;
    return {
      mode: candidate.mode === 'channel' ? 'channel' : 'search',
      requireHumanCaptions: candidate.requireHumanCaptions === true,
      hideLive: candidate.hideLive !== false,
    };
  } catch {
    return DEFAULT_PREFS;
  }
}

function writePrefs(prefs: YoutubePrefs): void {
  try {
    localStorage.setItem(PREFS_KEY, JSON.stringify(prefs));
  } catch {
    // Preferences are a convenience; losing them must never block the console.
  }
}

