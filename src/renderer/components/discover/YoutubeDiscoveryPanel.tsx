export function YoutubeDiscoveryControls({ state }: { state: YoutubeDiscoveryState }) {
  const { t } = useT();
  const {
    mode, setMode, query, setQuery, submit, loadState,
    requireHumanCaptions, setRequireHumanCaptions, hideLive, setHideLive,
  } = state;

  return (
    <div className="disc-controls">
      <div className="disc-searchline">
        <div className="disc-searchbox">
          <Icon name="search" size={13} />
          <input
            type="search"
            value={query}
            onChange={(e) => setQuery(e.target.value)}
            onKeyDown={(e) => {
              // Enter confirms an IME conversion; it must not search yet.
              if (e.nativeEvent.isComposing || e.nativeEvent.keyCode === 229) return;
              if (e.key === 'Enter') submit();
            }}
            placeholder={t(mode === 'channel'
              ? 'ytDiscovery.search.placeholderChannel'
              : 'ytDiscovery.search.placeholder')}
            aria-label={t('ytDiscovery.search.label')}
          />
        </div>
        <button
          type="button"
          className="disc-btn disc-btn-primary"
          onClick={submit}
          disabled={!query.trim() || loadState === 'loading'}
        >
          {t('ytDiscovery.search.run')}
        </button>
      </div>

      <div className="disc-filterline">
        <div className="disc-segment" role="group" aria-label={t('ytDiscovery.mode.label')}>
          {(['search', 'channel'] as const).map((id) => (
            <button
              key={id}
              type="button"
              className={`disc-seg-btn ${mode === id ? 'active' : ''}`}
              aria-pressed={mode === id}
              onClick={() => setMode(id)}
            >
              {t(`ytDiscovery.mode.${id}`)}
            </button>
          ))}
        </div>

        <label className="disc-check">
          <input
            type="checkbox"
            checked={requireHumanCaptions}
            onChange={(e) => setRequireHumanCaptions(e.target.checked)}
          />
          <span>{t('ytDiscovery.filter.humanCaptions')}</span>
        </label>

        <label className="disc-check">
          <input type="checkbox" checked={hideLive} onChange={(e) => setHideLive(e.target.checked)} />
          <span>{t('ytDiscovery.filter.hideLive')}</span>
        </label>
      </div>
    </div>
  );
}

export function YoutubeDiscoveryResults({ state }: { state: YoutubeDiscoveryState }) {
  const { t } = useT();
  const {
    results, selected, select, loadState, message, view, setView,
    shortlistIds, toggleShortlist, shortlist, busyVideoId, probe,
  } = state;

  const header = (
    <div className="disc-tabs" role="tablist">
      <button
        type="button"
        role="tab"
        aria-selected={view === 'results'}
        className={`disc-tab ${view === 'results' ? 'active' : ''}`}
        onClick={() => setView('results')}
      >
        {t('ytDiscovery.view.results')}
      </button>
      <button
        type="button"
        role="tab"
        aria-selected={view === 'shortlist'}
        className={`disc-tab ${view === 'shortlist' ? 'active' : ''}`}
        onClick={() => setView('shortlist')}
      >
        {t('ytDiscovery.view.shortlist')}
        {shortlist.length > 0 ? <span className="disc-tab-count">{shortlist.length}</span> : null}
      </button>
    </div>
  );

  let body: ReactNode;
  if (view === 'results' && loadState === 'loading') {
    body = <div className="disc-placeholder">{t('ytDiscovery.state.loading')}</div>;
  } else if (view === 'results' && loadState === 'tool-missing') {
    // The "not configured" state. This feature has no API key to be missing —
    // the only thing it can lack is the binary it shares with the downloader.
    body = (
      <div className="disc-placeholder disc-placeholder-error">
        {t('ytDiscovery.state.toolMissing')}
      </div>
    );
  } else if (view === 'results' && loadState === 'error') {
    body = (
      <div className="disc-placeholder disc-placeholder-error">
        {t('ytDiscovery.state.error')}{message ? ` — ${message}` : ''}
      </div>
    );
  } else if (view === 'results' && loadState === 'idle') {
    body = <div className="disc-placeholder">{t('ytDiscovery.state.idle')}</div>;
  } else if (results.length === 0) {
    body = (
      <div className="disc-placeholder">
        {view === 'shortlist' ? t('ytDiscovery.state.shortlistEmpty') : t('ytDiscovery.state.empty')}
      </div>
    );
  } else {
    body = (
      <div className="disc-table" role="table" aria-label={t('ytDiscovery.results.label')}>
        {/* Eight cells per row, matching `.disc-row`'s fixed grid. */}
        <div className="disc-row disc-row-head" role="row">
          <span>{t('scraper.column.rank')}</span>
          <span>{t('scraper.column.title')}</span>
          <span>{t('ytDiscovery.column.study')}</span>
          <span>{t('ytDiscovery.column.lang')}</span>
          <span>{t('ytDiscovery.column.captions')}</span>
          <span>{t('ytDiscovery.column.audio')}</span>
          <span>{t('ytDiscovery.column.length')}</span>
          <span />
        </div>
        {results.map((entry, index) => {
          const id = youtubeCandidateId(entry.candidate);
          const shortlisted = shortlistIds.has(id);
          const busy = busyVideoId === entry.candidate.videoId;
          return (
            <div
              key={id}
              role="row"
              className={`disc-row ${selected?.candidate.videoId === entry.candidate.videoId ? 'selected' : ''}`}
              onClick={() => select(entry.candidate.videoId)}
              onKeyDown={(e) => {
                if (e.key === 'Enter' || e.key === ' ') {
                  e.preventDefault();
                  select(entry.candidate.videoId);
                }
              }}
              tabIndex={0}
            >
              <span className="disc-cell-rank">{index + 1}</span>
              <span className="disc-cell-title">
                <strong>{entry.candidate.title}</strong>
                {entry.candidate.channelTitle ? <small>{entry.candidate.channelTitle}</small> : null}
              </span>
              <span className="disc-cell-match">
                <span className={`disc-meter disc-meter-${scoreBand(entry.studyScore)}`}>
                  <span style={{ width: `${entry.studyScore}%` }} />
                </span>
                <em>{Math.round(entry.studyScore)}</em>
              </span>
              <span className="disc-cell-level">
                <span className="disc-badge" title={captionLabel(entry, t)}>
                  {captionLangBadge(entry)}
                </span>
              </span>
              <span className="disc-cell-dim">{captionShort(entry, t)}</span>
              <span className="disc-cell-dim">{t(`ytDiscovery.audio.${entry.signals.audio}`)}</span>
              <span className="disc-cell-dim">{formatDuration(entry.candidate.durationSec)}</span>
              <span className="disc-cell-action">
                <button
                  type="button"
                  className="disc-pin"
                  disabled={busy || entry.probed}
                  title={t('ytDiscovery.action.probe')}
                  aria-label={t('ytDiscovery.action.probeRow', { title: entry.candidate.title })}
                  onClick={(e) => {
                    e.stopPropagation();
                    select(entry.candidate.videoId);
                    probe(entry.candidate.videoId);
                  }}
                >
                  <Icon name="search" size={12} />
                </button>
                <button
                  type="button"
                  className={`disc-pin ${shortlisted ? 'active' : ''}`}
                  title={shortlisted ? t('scraper.action.unshortlist') : t('scraper.action.shortlist')}
                  aria-label={t(
                    shortlisted ? 'scraper.action.unshortlistRow' : 'scraper.action.shortlistRow',
                    { title: entry.candidate.title },
                  )}
                  aria-pressed={shortlisted}
                  onClick={(e) => {
                    e.stopPropagation();
                    toggleShortlist(entry.candidate);
                  }}
                >
                  <Icon name="bookmark" size={12} />
                </button>
              </span>
            </div>
          );
        })}
      </div>
    );
  }

  return (
    <div className="disc-youtube">
      {header}
      {body}
    </div>
  );
}

export function YoutubeDiscoveryInspector({ state }: { state: YoutubeDiscoveryState }) {
  const { t } = useT();
  const {
    selected, insights, busyVideoId, probe, handoff, measurePace,
    notice, probeError, shortlistIds, toggleShortlist, channels,
  } = state;

  // Sort only — every label below is resolved through `t()` down in the JSX, so
  // the list re-renders in the new language on a switch without this memo
  // knowing about the language at all. (A memo that *did* build strings would
  // need `lang` in its deps, never `t`, whose identity is stable by design.)
  const reasons = useMemo(
    () => (selected ? [...selected.reasons].sort((a, b) => b.points - a.points) : []),
    [selected],
  );

  if (!selected) {
    return (
      <aside className="disc-inspector disc-inspector-empty" aria-label={t('ytDiscovery.inspector.label')}>
        <p>{t('ytDiscovery.inspector.hint')}</p>
      </aside>
    );
  }

  const { candidate, signals } = selected;
  const insight = insights[candidate.videoId] ?? {};
  const busy = busyVideoId === candidate.videoId;
  const shortlisted = shortlistIds.has(youtubeCandidateId(candidate));
  const channel = channels.get(candidate.channelId || candidate.channelTitle || '');

  return (
    <aside className="disc-inspector" aria-label={t('ytDiscovery.inspector.label')}>
      <div className="disc-insp-head">
        {candidate.thumbUrl ? (
          <img src={candidate.thumbUrl} alt="" loading="lazy" referrerPolicy="no-referrer" />
        ) : (
          <div className="disc-insp-noart"><Icon name="image" size={18} /></div>
        )}
        <div>
          <h2>{candidate.title}</h2>
          {candidate.channelTitle ? <p className="disc-insp-native">{candidate.channelTitle}</p> : null}
          <p className="disc-insp-meta">{formatDuration(candidate.durationSec)}</p>
        </div>
      </div>

      <div className="disc-insp-score">
        <span className={`disc-meter disc-meter-${scoreBand(selected.studyScore)}`}>
          <span style={{ width: `${selected.studyScore}%` }} />
        </span>
        <strong>{Math.round(selected.studyScore)}</strong>
        <small>{t('ytDiscovery.inspector.studyScore')}</small>
      </div>

      <section className="disc-insp-block">
        <h3>{t('ytDiscovery.inspector.signals')}</h3>
        <ul className="disc-reasons">
          <li>
            <span>{t('ytDiscovery.signal.captions')}</span>
            <em>{captionLabel(selected, t)}</em>
          </li>
          <li>
            <span>{t('ytDiscovery.signal.audio')}</span>
            <em>{t(`ytDiscovery.audio.${signals.audio}`)}</em>
          </li>
          <li>
            <span>{t('ytDiscovery.signal.pace')}</span>
            <em>
              {signals.pace === 'unknown'
                ? t('ytDiscovery.pace.unknown')
                : t(`ytDiscovery.pace.${signals.pace}`, {
                  rate: Math.round(signals.charsPerMinute ?? 0),
                })}
            </em>
          </li>
          {channel && channel.humanCaptionShare !== null ? (
            <li>
              <span>{t('ytDiscovery.signal.channel')}</span>
              <em>
                {t(
                  channel.humanCaptionShare >= CONSISTENT_CHANNEL_SHARE
                    ? 'ytDiscovery.channel.consistent'
                    : 'ytDiscovery.channel.mixed',
                  // `count` is the plural selector the catalogs key on, so the
                  // probed sample — not the caption hits — has to be the one
                  // named `count`, or Russian inflects on the wrong number.
                  { count: channel.probed, withCaptions: channel.withHumanTargetCaptions },
                )}
              </em>
            </li>
          ) : null}
        </ul>
        <p className="disc-insp-note">{t('ytDiscovery.inspector.estimateNote')}</p>
      </section>

      <section className="disc-insp-block">
        <h3>{t('scraper.inspector.why')}</h3>
        <ul className="disc-reasons">
          {reasons.map((reason) => (
            <li key={reason.code} className={reason.points < 0 ? 'negative' : ''}>
              <span>{reasonLabel(reason, t)}</span>
              <em>{reason.points > 0 ? `+${reason.points}` : reason.points}</em>
            </li>
          ))}
        </ul>
      </section>

      {notice ? <p className="disc-insp-note" role="status">{t(`ytDiscovery.notice.${notice}`)}</p> : null}
      {probeError && probeError.videoId === candidate.videoId ? (
        <p className="disc-insp-note disc-insp-error" role="alert">
          {probeError.message
            ? t('ytDiscovery.notice.probeFailedDetail', { detail: probeError.message })
            : t('ytDiscovery.notice.probeFailed')}
        </p>
      ) : null}

      <div className="disc-insp-actions">
        <button
          type="button"
          className="disc-btn disc-btn-primary"
          disabled={busy || selected.probed}
          onClick={() => probe(candidate.videoId)}
        >
          <Icon name="search" size={12} />
          {selected.probed ? t('ytDiscovery.action.probed') : t('ytDiscovery.action.probe')}
        </button>
        <button
          type="button"
          className="disc-btn"
          disabled={busy || Boolean(insight.managedVideoId)}
          onClick={() => handoff(candidate)}
        >
          <Icon name="library" size={12} />
          {insight.managedVideoId ? t('ytDiscovery.action.added') : t('ytDiscovery.action.addToManager')}
        </button>
        <button
          type="button"
          className="disc-btn"
          disabled={busy || !insight.managedVideoId || typeof insight.charsPerMinute === 'number'}
          title={insight.managedVideoId ? undefined : t('ytDiscovery.action.measurePaceHint')}
          onClick={() => measurePace(candidate)}
        >
          <Icon name="headphones" size={12} />
          {t('ytDiscovery.action.measurePace')}
        </button>
        <button
          type="button"
          className="disc-btn"
          onClick={() => toggleShortlist(candidate)}
        >
          <Icon name="bookmark" size={12} />
          {shortlisted ? t('scraper.action.unshortlist') : t('scraper.action.shortlist')}
        </button>
        <button
          type="button"
          className="disc-btn"
          onClick={() => void window.api?.openExternal?.(candidate.url)}
        >
          <Icon name="external" size={12} />
          {t('ytDiscovery.action.openOnYoutube')}
        </button>
      </div>
    </aside>
  );
}
