function scoreBand(score: number): 'high' | 'mid' | 'low' {
  if (score >= 70) return 'high';
  if (score >= 45) return 'mid';
  return 'low';
}

function formatDuration(seconds: number | undefined): string {
  if (typeof seconds !== 'number' || !Number.isFinite(seconds) || seconds <= 0) return '—';
  const total = Math.round(seconds);
  const h = Math.floor(total / 3600);
  const m = Math.floor((total % 3600) / 60);
  const s = total % 60;
  const pad = (value: number): string => String(value).padStart(2, '0');
  return h > 0 ? `${h}:${pad(m)}:${pad(s)}` : `${m}:${pad(s)}`;
}

type Translate = (key: string, vars?: Record<string, string | number>) => string;

function reasonLabel(reason: YoutubeReason, t: Translate): string {
  switch (reason.code) {
    case 'captions-human':
      return t('ytDiscovery.reason.captionsHuman', { langs: reason.detail ?? '' });
    case 'captions-auto':
      return t('ytDiscovery.reason.captionsAuto');
    case 'captions-none':
      return t('ytDiscovery.reason.captionsNone');
    case 'captions-unchecked':
      return t('ytDiscovery.reason.captionsUnchecked');
    case 'audio-target':
      return t('ytDiscovery.reason.audioTarget');
    case 'audio-other':
      return t('ytDiscovery.reason.audioOther');
    case 'japanese-title':
      return t('ytDiscovery.reason.japaneseTitle');
    case 'pace-fit':
      return t('ytDiscovery.reason.paceFit', { rate: reason.detail ?? '' });
    case 'pace-fast':
      return t('ytDiscovery.reason.paceFast', { rate: reason.detail ?? '' });
    case 'pace-slow':
      return t('ytDiscovery.reason.paceSlow', { rate: reason.detail ?? '' });
    case 'length-fit':
      return t('ytDiscovery.reason.lengthFit');
    case 'length-long':
      return t('ytDiscovery.reason.lengthLong');
    case 'channel-consistent':
      return t('ytDiscovery.reason.channelConsistent', { ratio: reason.detail ?? '' });
    case 'is-live':
    default:
      return t('ytDiscovery.reason.isLive');
  }
}

/** The long form, for the inspector and for the row's accessible name. */
function captionLabel(entry: YoutubeRanking, t: Translate): string {
  switch (entry.signals.captions) {
    case 'human-target':
      return t('ytDiscovery.captions.humanTarget');
    case 'human-other':
      return t('ytDiscovery.captions.humanOther', { langs: entry.signals.humanCaptionLangs.join(', ') });
    case 'auto-only':
      return t('ytDiscovery.captions.autoOnly');
    case 'none':
      return t('ytDiscovery.captions.none');
    case 'unknown':
    default:
      return t('ytDiscovery.captions.unchecked');
  }
}

/** The short form for the fixed-width table column. */
function captionShort(entry: YoutubeRanking, t: Translate): string {
  switch (entry.signals.captions) {
    case 'human-target':
    case 'human-other':
      return t('ytDiscovery.captions.short.human');
    case 'auto-only':
      return t('ytDiscovery.captions.short.auto');
    case 'none':
      return t('ytDiscovery.captions.short.none');
    case 'unknown':
    default:
      return t('ytDiscovery.captions.short.unchecked');
  }
}

/**
 * The caption language badge. A language tag, not chrome, so it is shown
 * verbatim rather than translated — `ja` means the same thing in all four UI
 * languages, and `—` is an absence, not a word.
 */
function captionLangBadge(entry: YoutubeRanking): string {
  if (entry.signals.humanCaptionLangs.length > 0) return entry.signals.humanCaptionLangs.join('/');
  if (entry.signals.captions === 'unknown') return '?';
  return '—';
}

