// A curated browser of Japanese novels & light novels for immersion reading.
// Every entry is a real, well-known work. Metadata (genre, difficulty, year) is
// hand-checked; difficulty is a reading-difficulty *guide* for learners, not an
// official score. Links open in the system browser via window.api.openExternal.
//
// To add a book: copy an entry, fill it in, and it shows up automatically.
// Difficulty guide:
//   Beginner  – simple, often children's; good first native reads
//   Easy      – modern, dialogue-heavy, limited rare vocab (~N3)
//   Moderate  – standard adult prose / typical light novel (~N3–N2)
//   Hard      – dense or stylistic literary prose (~N2–N1)
//   Very Hard – archaic, classical (bungo) or heavy wordplay (N1+)

export type NovelType = 'Classic' | 'Novel' | 'Light Novel';
export type Difficulty = 'Beginner' | 'Easy' | 'Moderate' | 'Hard' | 'Very Hard';
export type LinkKind = 'free' | 'store' | 'info';

export const NOVEL_TYPES: NovelType[] = ['Classic', 'Novel', 'Light Novel'];
export const DIFFICULTY_ORDER: Difficulty[] = ['Beginner', 'Easy', 'Moderate', 'Hard', 'Very Hard'];

export const GENRES = [
  'Literary',
  'Coming-of-age',
  'Mystery',
  'Thriller',
  'Sci-Fi',
  'Fantasy',
  'Isekai',
  'Romance',
  'Slice of Life',
  'Comedy',
  'Horror',
  'Historical',
  "Children's",
  'Action',
] as const;
export type Genre = (typeof GENRES)[number];

export interface NovelLink {
  label: string;
  url: string;
  kind: LinkKind;
}

export interface Novel {
  id: string;
  titleJp: string;
  /** Kana reading of the title, for furigana-less learners. */
  reading?: string;
  /** Common English title (official where one exists, else a literal gloss). */
  titleEn?: string;
  author: string;
  authorEn?: string;
  type: NovelType;
  genres: Genre[];
  /** First publication year (of the first volume, for series). */
  year?: number;
  difficulty: Difficulty;
  /** Rough JLPT level at which the book becomes comfortable. */
  jlpt?: 'N5' | 'N4' | 'N3' | 'N2' | 'N1';
  /** True when the full text is legally free on Aozora Bunko. */
  freeOnAozora: boolean;
  synopsis: string;
  links: NovelLink[];
}

// ---- link builders (search-based, so they never rot into dead URLs) --------

/** Find the free full text on Aozora Bunko. */
function free(title: string, author: string): NovelLink {
  const q = `${title} ${author} site:aozora.gr.jp`;
  return { label: 'Read free · Aozora Bunko', url: `https://duckduckgo.com/?q=${encodeURIComponent(q)}`, kind: 'free' };
}
/** Find the e-book to buy/read (BookWalker has a big JP + light-novel catalogue). */
function store(title: string): NovelLink {
  return {
    label: 'Find the book · BookWalker',
    url: `https://global.bookwalker.jp/search/?word=${encodeURIComponent(title)}`,
    kind: 'store',
  };
}
/** Background, genre and series info on the Japanese Wikipedia. */
function info(title: string, author: string): NovelLink {
  return {
    label: 'Details · Wikipedia',
    url: `https://ja.wikipedia.org/w/index.php?search=${encodeURIComponent(`${title} ${author}`)}`,
    kind: 'info',
  };
}

/** Classics: free Aozora text + info. Modern works: store + info. */
function links(n: { titleJp: string; author: string; freeOnAozora: boolean }): NovelLink[] {
  return n.freeOnAozora
    ? [free(n.titleJp, n.author), info(n.titleJp, n.author)]
    : [store(n.titleJp), info(n.titleJp, n.author)];
}

// Build a full Novel from a compact spec (auto-fills id + links).
type Spec = Omit<Novel, 'id' | 'links'> & { id?: string };
function n(spec: Spec): Novel {
  const id = spec.id ?? spec.titleJp;
  return { ...spec, id, links: links(spec) };
}

