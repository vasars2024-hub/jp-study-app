function wordsToRanks(words: readonly string[]): Record<string, number> {
  const ranks: Record<string, number> = {};
  words.forEach((word, index) => {
    const w = word.trim();
    if (w) ranks[w] = index + 1;
  });
  return ranks;
}

export function bundledFrequencyRankMaps(): Array<{
  def: BundledFrequencyDictionary;
  ranks: Record<string, number>;
}> {
  return BUNDLED_FREQUENCY_DICTIONARIES.map((def) => ({
    def,
    ranks: wordsToRanks(def.words),
  }));
}

export function isBundledFrequencyDictId(id: string): boolean {
  return id.startsWith('bundled-freq-');
}
