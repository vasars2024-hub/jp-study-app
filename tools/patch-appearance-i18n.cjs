function formatBlock(lang, map) {
  const lines = [`  // Settings > Appearance (${lang})`];
  for (const [k, v] of Object.entries(map)) {
    lines.push(`  '${k}': '${v.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}',`);
  }
  return lines.join('\n');
}

const blocks = {
  en: formatBlock('en', en),
  ja: formatBlock('ja', ja),
  zh: formatBlock('zh', zh),
  ru: formatBlock('ru', ru),
};

const markers = {
  en: "    'The language of the app itself. This does not change the language you are studying.',",
  ja: "  'settings.language.desc': 'アプリ自体の表示言語です。学習する言語は変わりません。',",
  zh: "  'settings.language.desc': '应用界面的语言。这不会改变你正在学习的语言。',",
  ru: "    'Язык самого приложения. Это не меняет язык, который вы изучаете.',",
};

// Insert after settings.language block in each lang section
for (const [lang, marker] of Object.entries(markers)) {
  const tag = `// Settings > Appearance (${lang})`;
  if (text.includes(tag)) {
    console.log('skip', lang);
    continue;
  }
  const idx = text.indexOf(marker);
  if (idx < 0) throw new Error(`marker missing: ${lang}`);
  const lineEnd = text.indexOf('\n', idx);
  const block = '\n' + blocks[lang] + '\n';
  text = text.slice(0, lineEnd) + block + text.slice(lineEnd);
}

fs.writeFileSync(catalogsPath, text);
console.log('done');
