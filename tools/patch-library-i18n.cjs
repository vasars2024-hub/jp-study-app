const packs = { en, ja, zh, ru };

for (const [lang, map] of Object.entries(packs)) {
  const tag = `  // Library view (${lang})`;
  if (text.includes(tag)) {
    console.log('skip', lang);
    continue;
  }
  const marker = '  // Resources view';
  // Each language block has its own "// Resources view" — insert before the
  // Nth occurrence (0=en, 1=ja, 2=zh, 3=ru).
  const langIndex = { en: 0, ja: 1, zh: 2, ru: 3 }[lang];
  let from = 0;
  let idx = -1;
  for (let i = 0; i <= langIndex; i++) {
    idx = text.indexOf(marker, from);
    if (idx < 0) throw new Error(`marker missing for ${lang} (#${i})`);
    from = idx + marker.length;
  }
  text = text.slice(0, idx) + formatBlock(lang, map) + '\n\n' + text.slice(idx);
}

fs.writeFileSync(catalogsPath, text);
