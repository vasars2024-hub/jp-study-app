for (const lang of ['en', 'ja', 'zh', 'ru']) {
  const tag = `// Settings > Display/Desktop/Lock (${lang})`;
  if (text.includes(tag)) {
    console.log('skip', lang);
    continue;
  }
  const marker = insertAfter[lang];
  const idx = text.indexOf(marker);
  if (idx < 0) throw new Error(`marker missing: ${lang}`);
  const end = idx + marker.length;
  text = text.slice(0, end) + '\n' + formatBlock(lang, packs[lang]) + '\n' + text.slice(end);
}

fs.writeFileSync(catalogsPath, text);
console.log('patched display/desktop/lock keys');
