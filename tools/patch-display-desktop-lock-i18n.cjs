function formatBlock(lang, map) {
  const lines = [`  // Settings > Display/Desktop/Lock (${lang})`];
  for (const [k, v] of Object.entries(map)) {
    const esc = String(v).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
    if (esc.length > 90 && !esc.includes('{')) {
      // keep as single line for simplicity
    }
    lines.push(`  '${k}': '${esc}',`);
  }
  return lines.join('\n');
}

