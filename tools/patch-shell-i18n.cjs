function formatBlock(comment, map) {
  const lines = [`  // ${comment}`];
  for (const [k, v] of Object.entries(map)) {
    const esc = v.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
    lines.push(`  '${k}': '${esc}',`);
  }
  return lines.join('\n');
}

