function formatBlock(lang, map) {
  return ['  // Settings > Mini/Shortcuts/Reader (' + lang + ')']
    .concat(
      Object.entries(map).map(([k, v]) => {
        const esc = String(v).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
        return `  '${k}': '${esc}',`;
      }),
    )
    .join('\n');
}

