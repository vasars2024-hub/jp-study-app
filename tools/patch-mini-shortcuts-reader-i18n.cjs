for (const lang of Object.keys(markers)) {
  const tag = `// Settings > Mini/Shortcuts/Reader (${lang})`;
  if (text.includes(tag)) {
    console.log('skip', lang);
    continue;
  }
  const m = markers[lang];
  const i = text.indexOf(m);
  if (i < 0) throw new Error('marker ' + lang);
  text = text.slice(0, i + m.length) + '\n' + formatBlock(lang, packs[lang]) + '\n' + text.slice(i + m.length);
}

